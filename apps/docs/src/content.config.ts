import { defineCollection } from "astro:content";
import { readFile } from "node:fs/promises";
import { docsLoader } from "@astrojs/starlight/loaders";
import { docsSchema } from "@astrojs/starlight/schema";
import type { Loader } from "astro/loaders";
import { autoSidebarLoader } from "starlight-auto-sidebar/loader";
import { autoSidebarSchema } from "starlight-auto-sidebar/schema";
import { mcpTools, toolPage } from "./lib/mcp.ts";
import { MCP_OUTPUT } from "./lib/mcp-output.ts";

/**
 * Every page in src/content/docs/, then one page per MCP tool in public/mcp-tools.json at
 * `mcp/<tool>` (dl-5ssh.90.8), so a new tool is a new page with no other edit. scripts/prepare.ts
 * copies the file in before every build.
 */
function docsAndMcpTools(): Loader {
  const docs = docsLoader();
  return {
    name: "jadwigo-docs",
    load: async (context) => {
      await docs.load(context);
      const path = new URL("public/mcp-tools.json", context.config.root);
      const text = await readFile(path, "utf8").catch(() => {
        throw new Error(`${path.pathname} is missing: run bun scripts/prepare.ts`);
      });
      for (const tool of mcpTools(JSON.parse(text))) {
        const page = toolPage(tool, MCP_OUTPUT[tool.name]);
        const data = await context.parseData({
          id: page.id,
          data: { title: page.title, description: page.description },
        });
        // Where the page would sit as a file: Starlight's autogenerated sidebar and the links
        // validator know a page by it.
        const filePath = `src/content/docs/${page.id}.md`;
        context.store.set({
          id: page.id,
          data,
          filePath,
          body: page.body,
          rendered: await context.renderMarkdown(page.body, {
            fileURL: new URL(filePath, context.config.root),
          }),
          digest: context.generateDigest(page.body),
        });
      }
    },
  };
}

/**
 * Every page, whose entry id is its slug, and every `_meta.yml` in src/content/docs/, which
 * starlight-auto-sidebar reads to order an autogenerated sidebar group.
 */
export const collections = {
  docs: defineCollection({ loader: docsAndMcpTools(), schema: docsSchema() }),
  autoSidebar: defineCollection({ loader: autoSidebarLoader(), schema: autoSidebarSchema() }),
};
