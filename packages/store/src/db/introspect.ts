/** A column as the migrations made it, read from the catalog. */
interface Column {
  /** The Postgres type: `uuid`, `text`, `int4`, `bool`, `timestamptz`, `jsonb`, an enum's name, or `_text`. */
  readonly type: string;
  readonly nullable: boolean;
  /** It has a default, so an insert may leave it out. */
  readonly generated: boolean;
  /** An enum's labels in order, or null. */
  readonly labels: readonly string[] | null;
}

/** Every table and view the migrations made in `public`, by name, each with its columns in order. */
export type Columns = Readonly<Record<string, Readonly<Record<string, Column>>>>;

interface Queryable {
  query<R>(text: string): Promise<{ rows: R[] }>;
}

interface CatalogRow {
  relation: string;
  column: string;
  type: string;
  nullable: boolean;
  generated: boolean;
  labels: string[] | null;
}

/** The schema `make migrate` built, as the generated types and the drift check see it. */
export async function introspect(db: Queryable): Promise<Columns> {
  const { rows } = await db.query<CatalogRow>(`
    select c.relname as relation, a.attname as column, t.typname as type,
      not a.attnotnull as nullable, a.atthasdef as generated,
      (select array_agg(e.enumlabel::text order by e.enumsortorder)
        from pg_enum as e where e.enumtypid = t.oid) as labels
    from pg_class as c
    join pg_namespace as n on n.oid = c.relnamespace
    join pg_attribute as a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    join pg_type as t on t.oid = a.atttypid
    where n.nspname = 'public' and c.relkind in ('r', 'v')
      -- An extension's own, such as pgTAP's views after \`make pgtap\`, is not the schema's.
      and not exists (select from pg_depend as d where d.objid = c.oid and d.deptype = 'e')
    order by c.relname, a.attnum
  `);
  const columns: Record<string, Record<string, Column>> = {};
  for (const row of rows) {
    const table = columns[row.relation] ?? {};
    columns[row.relation] = table;
    table[row.column] = {
      type: row.type,
      nullable: row.nullable,
      generated: row.generated,
      labels: row.labels,
    };
  }
  return columns;
}

/** A Postgres type as TypeScript: what a select reads, and what an insert or update writes. */
const TS_TYPES: Readonly<Record<string, { readonly read: string; readonly write: string }>> = {
  uuid: { read: "string", write: "string" },
  text: { read: "string", write: "string" },
  int4: { read: "number", write: "number" },
  float8: { read: "number", write: "number" },
  bool: { read: "boolean", write: "boolean" },
  // pg reads a timestamptz as a Date; a write may send ISO text.
  timestamptz: { read: "Date", write: "Date | string" },
  // pg reads jsonb as JSON; a write sends text, since pg would turn a JS array into a Postgres one.
  jsonb: { read: "unknown", write: "string" },
  _text: { read: "string[]", write: "string[]" },
};

function pascal(name: string): string {
  return name.replace(/(?:^|_)([a-z])/g, (_, c: string) => c.toUpperCase());
}

function tsType(column: Column): string {
  const enumName = column.labels ? pascal(column.type) : undefined;
  const types = enumName ? { read: enumName, write: enumName } : TS_TYPES[column.type];
  if (!types) throw new Error(`no TypeScript type for the Postgres type ${column.type}`);
  const orNull = column.nullable ? " | null" : "";
  const read = `${types.read}${orNull}`;
  const write = `${types.write}${orNull}`;
  if (read === write) return column.generated ? `Generated<${read}>` : read;
  const insert = column.generated ? `${write} | undefined` : write;
  return `ColumnType<${read}, ${insert}, ${write}>`;
}

/** `src/db/types.ts`: Kysely's `DB` for the schema, and the columns it came from. */
export function render(columns: Columns): string {
  const enums = new Map<string, readonly string[]>();
  for (const table of Object.values(columns)) {
    for (const column of Object.values(table)) {
      if (column.labels) enums.set(column.type, column.labels);
    }
  }
  const lines = [
    "// Generated by `bun run db:types` (src/db/generate.ts) from the database `make migrate` builds.",
    "// Never edited by hand: postgres.int.test.ts fails when it no longer matches the migrations.",
    'import type { ColumnType, Generated } from "kysely";',
    'import type { Columns } from "./introspect.ts";',
    "",
  ];
  for (const [name, labels] of [...enums].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`type ${pascal(name)} = ${labels.map((l) => JSON.stringify(l)).join(" | ")};`);
  }
  for (const [table, cols] of Object.entries(columns)) {
    lines.push("", `interface ${pascal(table)}Table {`);
    for (const [name, column] of Object.entries(cols)) lines.push(`  ${name}: ${tsType(column)};`);
    lines.push("}");
  }
  lines.push("", "export interface DB {");
  for (const table of Object.keys(columns)) lines.push(`  ${table}: ${pascal(table)}Table;`);
  lines.push(
    "}",
    "",
    `export const COLUMNS = ${JSON.stringify(columns)} as const satisfies Columns;`,
    "",
  );
  return lines.join("\n");
}
